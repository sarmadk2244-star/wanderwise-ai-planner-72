/**
 * Returns a URL to a real Flickr photo matching the tag.
 * LoremFlickr searches Flickr's CC-licensed pool by tag and returns a relevant image.
 */
const ux = (tags: string, w = 1600, h = 1000, lockSeed?: string) => {
  const base = `https://loremflickr.com/${w}/${h}/${encodeURIComponent(tags)}/all`;
  return lockSeed ? `${base}?lock=${encodeURIComponent(lockSeed)}` : base;
};

const galleryFor = (city: string, themes: string[]) =>
  themes.map((t, i) => ux(`${city},${t}`, 1400, 900, `${city}-${t}-${i}`));

const defaultThemes = ["famous landmark", "scenic viewpoint", "street food", "traditional culture", "old town architecture", "festival people"];

export type Destination = {
  id: string;
  city: string;
  country: string;
  region: "Pakistan" | "International";
  image: string;            // hero
  gallery: string[];        // 6 gallery images
  tagline: string;
  description: string;
  bestSeason: string;
  estCost: string;
  budget: { flights: string; stay: string; food: string; activities: string };
  weather: string;
  weatherDetail: { temp: string; humidity: string; wind: string };
  highlights: string[];
  hotels: string[];
  restaurants: string[];
  culture: string;
  tips: string[];
  safety: number;            // 1–5
  transport: string;
  // International extras
  visa?: string;
  flight?: string;
  currency?: string;
};

type Seed = Omit<Destination, "image" | "gallery"> & {
  image?: string;
  gallery?: string[];
};

const make = (s: Seed): Destination => ({
  ...s,
  image: s.image ?? ux(`${s.city},${s.country},famous landmark`, 1600, 1100, `${s.id}-hero`),
  gallery: s.gallery ?? galleryFor(`${s.city} ${s.country}`, defaultThemes),
});

